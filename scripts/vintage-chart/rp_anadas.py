def _norm(s):
    if not s: return ""
    s = unicodedata.normalize("NFD", str(s))
    s = "".join(c for c in s if unicodedata.category(c) != "Mn").lower()
    return re.sub(r"[^a-z0-9]+", " ", s).strip()

def _band(score):
    if score >= 96: return "Extraordinaria"
    if score >= 90: return "Excepcional"
    if score >= 80: return "Muy buena a excelente"
    if score >= 70: return "Media"
    if score >= 60: return "Por debajo del promedio"
    return "Deficiente"

_MAT = {
    "T": "Aún tánica / joven, de guarda",
    "R": "Lista para beber",
    "E": "De maduración temprana, accesible",
    "C": "Precaución, puede estar pasada",
    "I": "Añada irregular, incluso entre los mejores",
}
_CELL = re.compile(r"^(\d{2,3})(?:-(\d{2,3}))?([TRECI])?$")

def _match_region(region_origin, name, category=None):
    r = _norm(region_origin)
    g = _norm((name or ""))
    white_re = re.compile(r"\b(blanc|blanco|bianco|white|chardonnay|sauvignon blanc|riesling|albarino|verdejo|chenin|gewurztraminer|pinot grigio|pinot gris|rose|rosado)\b")
    is_white = category in ("vino_blanco","espumoso","vino_naranja","vino_rosado") or bool(white_re.search(g))
    has = lambda n: n in r
    some = lambda xs: any(x in r for x in xs)

    north = ["napa","sonoma","knights valley","alexander valley","russian river","rutherford","oakville","howell mountain","mount veeder","stags leap","carneros","calistoga","st helena","spring mountain","diamond mountain"]
    if some(north):
        if "zinfandel" in g: return "us-north-zin"
        if "pinot noir" in g or "pinot nero" in g: return "us-north-pinot"
        if "chardonnay" in g: return "us-north-chard"
        if is_white: return None
        return "us-north-cab"
    if has("paso robles"): return "us-paso-robles"
    if some(["santa barbara","santa rita","sta rita","santa maria","edna valley","monterey","central coast","san luis obispo","arroyo grande"]): return "us-central-coast"
    if some(["willamette","yamhill","dundee","oregon","eola"]): return "us-willamette"

    if some(["pessac","leognan","graves"]): return "bordeaux-graves"
    if has("emilion"): return "bordeaux-st-emilion"
    if some(["sauternes","barsac"]): return "bordeaux-sauternes"
    if some(["pauillac","saint julien","st julien","saint estephe","st estephe","medoc"]): return "bordeaux-medoc-north"

    if some(["beaujolais","fleurie","morgon","moulin a vent","brouilly","julienas"]): return "beaujolais"
    bwhite = ["meursault","chassagne","puligny","montrachet","chablis","macon","pouilly fuisse","saint veran","corton charlemagne"]
    if some(bwhite): return "burgundy-white"
    nuits = ["gevrey","chambertin","chambolle","musigny","vosne","romanee","vougeot","nuits st","morey","flagey","marsannay","fixin"]
    if some(nuits): return "burgundy-nuits-red"
    beaune = ["pommard","volnay","beaune","corton","mercurey","savigny","monthelie"]
    if some(beaune):
        return "burgundy-white" if (is_white or "chardonnay" in g) else "burgundy-beaune-red"
    if has("burgundy") or has("bourgogne"):
        if any(x in g for x in ["chablis","chardonnay","blanc","meursault","montrachet"]): return "burgundy-white"
        if any(x in g for x in nuits): return "burgundy-nuits-red"
        if any(x in g for x in ["beaune","pommard","volnay"]): return "burgundy-beaune-red"
        return None

    if has("champagne"): return "champagne"
    if some(["sancerre","pouilly fume","vouvray","muscadet","touraine","savenniere","quincy"]): return "loire-white"
    if some(["cote rotie","hermitage","cornas","saint joseph","st joseph","crozes","condrieu"]): return "rhone-north"
    if some(["alsace","riquewihr","ribeauville"]): return "alsace"
    if some(["languedoc","picpoul","pinet","corbieres","minervois","faugeres","fitou","saint chinian"]): return "languedoc"

    if has("barbaresco"): return "piedmont-barbaresco"
    if has("barolo"): return "piedmont-barolo"
    if has("collio") or has("friuli"): return "friuli-collio"
    if has("etna") or (has("sicil") and not is_white): return "sicily-etna"
    if has("tuscany") or has("toscana") or has("chianti") or has("brunello") or has("bolgheri"):
        if "chianti" in r or "chianti" in g: return "tuscany-chianti"
